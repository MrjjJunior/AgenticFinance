"""
One-time setup: provision the entire XRPL Testnet multi-sig environment.

WHAT IT DOES
------------
1. Funds a fresh main (Stokvel pool) account from the Testnet faucet.
2. Creates the Human Owner, Agent, and Policy Co-Signer wallets.
3. Sets the SignerListSet on the main account:
       Human Owner  weight 2   (can countersign escalated txs alone)
       Agent        weight 1
       Co-Signer    weight 1   (quorum = 2, master key disabled)
4. Disables the main account's master key (only signers can act).
5. Writes a ready-to-use .env next to this script.

WHY: running the app with placeholder seeds crashes with
     `ValueError: Invalid character 'O'` because XRPL base58 seeds can
     never contain the characters 0, O, I or l.

Run from procurement_agent/:
    .\\venv\\Scripts\\python setup_wallets.py            (Windows)
    venv/bin/python setup_wallets.py                     (Linux/macOS)

Use --force to overwrite an existing .env.

Testnet only. Never reuse these keys on Mainnet.
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

from xrpl.clients import JsonRpcClient
from xrpl.models.transactions import SignerEntry, SignerListSet
from xrpl.models.transactions.account_set import AccountSet, AccountSetAsfFlag
from xrpl.transaction import submit_and_wait
from xrpl.wallet import Wallet, generate_faucet_wallet

TESTNET_URL = "https://s.altnet.rippletest.net:51234/"
ENV_PATH = Path(__file__).resolve().parent / ".env"


def step(msg: str) -> None:
    print(f"\n=== {msg}")


def main() -> int:
    if ENV_PATH.exists() and "--force" not in sys.argv:
        print(f"ERROR: {ENV_PATH} already exists.")
        print("Delete it first, or re-run with --force to overwrite.")
        return 1

    client = JsonRpcClient(TESTNET_URL)

    step("1/5 Funding main (Stokvel pool) account from Testnet faucet...")
    main_wallet = _fund("MAIN")
    print(f"    Main account : {main_wallet.classic_address}")

    step("2/5 Creating signer wallets (no funds needed for signers)...")
    human_wallet = Wallet.create()
    agent_wallet = Wallet.create()
    cosigner_wallet = Wallet.create()
    print(f"    Human Owner  : {human_wallet.classic_address}  (weight 2)")
    print(f"    Agent        : {agent_wallet.classic_address}  (weight 1)")
    print(f"    Co-Signer    : {cosigner_wallet.classic_address}  (weight 1)")

    step("3/5 Submitting SignerListSet (quorum = 2)...")
    signer_list_tx = SignerListSet(
        account=main_wallet.classic_address,
        signer_quorum=2,
        signer_entries=[
            SignerEntry(account=human_wallet.classic_address, signer_weight=2),
            SignerEntry(account=agent_wallet.classic_address, signer_weight=1),
            SignerEntry(account=cosigner_wallet.classic_address, signer_weight=1),
        ],
    )
    response = submit_and_wait(signer_list_tx, client, main_wallet)
    result = response.result["meta"]["TransactionResult"]
    if result != "tesSUCCESS":
        print(f"    ERROR: SignerListSet failed: {result}")
        return 1
    print(f"    Result: {result}")

    step("4/5 Disabling the main account master key...")
    disable_tx = AccountSet(
        account=main_wallet.classic_address,
        set_flag=AccountSetAsfFlag.ASF_DISABLE_MASTER,
    )
    response = submit_and_wait(disable_tx, client, main_wallet)
    result = response.result["meta"]["TransactionResult"]
    if result != "tesSUCCESS":
        print(f"    ERROR: DisableMasterKey failed: {result}")
        return 1
    print(f"    Result: {result}")

    step("5/5 Writing .env ...")
    env_content = f"""\
# Generated by setup_wallets.py on {time.strftime('%Y-%m-%d %H:%M')}
# Testnet ONLY – never use these keys on Mainnet.

XRPL_NODE_URL={TESTNET_URL}
MAIN_ACCOUNT_ADDRESS={main_wallet.classic_address}

RLUSD_CURRENCY_HEX=524C555344000000000000000000000000000000
RLUSD_ISSUER=rQhWct2fv4Vc4KRjRgMrxa8xPN9Zx9iLKV

AGENT_SEED={agent_wallet.seed}
POLICY_COSIGNER_SEED={cosigner_wallet.seed}
HUMAN_OWNER_SEED={human_wallet.seed}

GROQ_API_KEY=gsk-PLACEHOLDER
LLM_MODEL=llama-3.3-70b-versatile

DAILY_SPENDING_CAP_RLUSD=5000.00
APPROVED_SUPPLIER_ADDRESSES=rSupplierAlpha000000000000000000
KYB_CREDENTIAL_TYPE=KYBVerified

LOG_LEVEL=INFO
LOG_FORMAT=text
"""
    ENV_PATH.write_text(env_content, encoding="utf-8")
    print(f"    Wrote {ENV_PATH}")

    print("\nSETUP COMPLETE. Summary:")
    print(f"   Main account (funds, master key DISABLED): {main_wallet.classic_address}")
    print(f"   Human Owner (weight 2, countersigns Path B): {human_wallet.classic_address}")
    print(f"   Agent       (weight 1)                     : {agent_wallet.classic_address}")
    print(f"   Co-Signer   (weight 1)                     : {cosigner_wallet.classic_address}")
    print(f"   Human Owner seed (keep safe, needed to countersign escalated txs): {human_wallet.seed}")
    print("\nNext steps:")
    print("  1. Restart the server:  .\\venv\\Scripts\\python -m uvicorn app.main:app --reload")
    print("  2. Open frontend/index.html and click 'Load demo data' → 'Process invoice'.")
    print("     A REJECTED result (no KYB credential) is expected until you set up a")
    print("     real supplier account on Testnet and allowlist it.")
    return 0


def _fund(label: str) -> Wallet:
    """Request a funded wallet from the Testnet faucet (with retries)."""
    client = JsonRpcClient(TESTNET_URL)
    for attempt in range(1, 4):
        try:
            return generate_faucet_wallet(client)
        except Exception as exc:  # noqa: BLE001
            if attempt == 3:
                raise
            print(f"    [{label}] faucet attempt {attempt} failed: {exc}")
            print(f"    [{label}] may be rate-limited – retrying in 10s...")
            time.sleep(10)


if __name__ == "__main__":
    try:
        sys.exit(main())
    except KeyboardInterrupt:
        print("\nAborted.")
        sys.exit(130)
